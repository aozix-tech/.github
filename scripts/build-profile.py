def focus(mobile: bool = False) -> str:
    width, height = (640, 652) if mobile else (1200, 244)
    cards = [
        ('01 / BUILD', 'Software with purpose.', 'Web platforms and mobile apps,', 'shaped around real needs.'),
        ('02 / EXPLORE', 'Intelligence, applied.', 'Practical AI tools and automation', 'for more meaningful work.'),
        ('03 / PLAY', 'A little more delight.', 'Approachable games and thoughtful', 'interactive experiences.'),
    ]
    body = ''
    for i, (label, title, line1, line2) in enumerate(cards):
        x, y, w, h = (0, i*224, 640, 204) if mobile else (i*408, 0, 384, 244)
        body += f'<g transform="translate({x} {y})"><rect x=".5" y=".5" width="{w-1}" height="{h-1}" rx="18" fill="url(#panel)" stroke="#302638"/>'
        body += f'<path d="M27 1H{w-27}" stroke="url(#accent)" opacity=".45"/>'
        body += text(29, 42, label, 12, '#b8a4d9', extra='letter-spacing="2"')
        body += icon(i, w-93, 17)
        body += text(29, 98 if mobile else 116, title, 30 if mobile else 27, '#ece6f5', '500', 'letter-spacing="-.7"')
        body += text(29, 140 if mobile else 161, line1, 23 if mobile else 19)
        body += text(29, 174 if mobile else 191, line2, 23 if mobile else 19)
        body += '</g>'
    return wrap(width, height, 'What we build', 'Software with purpose. Intelligence, applied. A little more delight.', body)


def main() -> None:
    ASSETS.mkdir(parents=True, exist_ok=True)
    (ROOT / 'profile' / 'README.md').write_text(PROFILE, encoding='utf-8')
    for name, svg in {'hero.svg': hero(), 'hero-mobile.svg': hero(True),
                      'focus.svg': focus(), 'focus-mobile.svg': focus(True)}.items():
        (ASSETS / name).write_text(svg, encoding='utf-8')
        print(f'Generated profile/assets/{name}')


if __name__ == '__main__':
    main()
