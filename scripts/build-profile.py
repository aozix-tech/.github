def text(x: float, y: float, value: str, size: int = 20,
         fill: str = '#a9a3b8', weight: str = '400', extra: str = '') -> str:
    return (f'<text x="{x}" y="{y}" fill="{fill}" font-size="{size}" '
            f'font-weight="{weight}" {extra}>{escape(value)}</text>')


def defs() -> str:
    return '''<defs>
<linearGradient id="accent" x1="0" y1="0" x2="1" y2="0"><stop stop-color="#efe4ff"/><stop offset=".46" stop-color="#bea2ff"/><stop offset="1" stop-color="#88acff"/></linearGradient>
<linearGradient id="wire" x1="0" y1="0" x2="1" y2="1"><stop stop-color="#bb99ff"/><stop offset=".55" stop-color="#bca4f2"/><stop offset="1" stop-color="#77a6ff"/></linearGradient>
<radialGradient id="glow"><stop stop-color="#5a3585" stop-opacity=".34"/><stop offset=".6" stop-color="#37224f" stop-opacity=".15"/><stop offset="1" stop-color="#07080c" stop-opacity="0"/></radialGradient>
<linearGradient id="panel" x1="0" y1="0" x2="1" y2="1"><stop stop-color="#15121f"/><stop offset="1" stop-color="#0b0c12"/></linearGradient>
</defs>'''


def wrap(width: int, height: int, title: str, description: str, body: str) -> str:
    return (f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" '
            f'viewBox="0 0 {width} {height}" role="img" aria-labelledby="title desc">\n'
            f'<title id="title">{escape(title)}</title><desc id="desc">{escape(description)}</desc>\n'
            + defs() + '\n<g font-family="Helvetica Neue, Arial, sans-serif">\n'
            + body + '\n</g></svg>\n')


def orbit(cx: int, cy: int, scale: float) -> str:
    """Orthographic torus curves, matching the website's particle sculpture."""
    ellipses = []
    for i in range(26):
        v = 2 * pi * i / 26
        r = 159 + 53 * cos(v)
        y = -53 * sin(v) * .81
        ellipses.append(f'<ellipse cx="0" cy="{y:.2f}" rx="{r:.2f}" ry="{r*.59:.2f}"/>')
    geometry = ''.join(ellipses)
    meridians = []
    for i in range(20):
        u = 2 * pi * i / 20
        points = []
        for j in range(41):
            v = 2 * pi * j / 40
            r = 159 + 53 * cos(v)
            x, y = r*cos(u), r*sin(u)*.59 - 53*sin(v)*.81
            points.append(f'{x:.1f},{y:.1f}')
        meridians.append('<polyline points="' + ' '.join(points) + '"/>')
    return (f'<g transform="translate({cx} {cy}) rotate(-28) scale({scale})" fill="none">'
            '<g stroke="url(#wire)" stroke-width=".7" opacity=".38">' + geometry + '</g>'
            '<g stroke="#c8b6ff" stroke-width="2" stroke-linecap="round" stroke-dasharray=".01 13" opacity=".50">' + geometry + '</g>'
            '<g stroke="url(#wire)" stroke-width=".5" opacity=".17">' + ''.join(meridians) + '</g></g>')


